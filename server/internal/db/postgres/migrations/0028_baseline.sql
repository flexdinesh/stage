-- +goose Up
-- Postgres baseline (#403): the SQLite schema at 0028 in Postgres-native
-- types (docs/storage.md "Encodings"): timestamptz, jsonb (text for
-- evidence bytes), boolean, bytea, identity IDs (BY DEFAULT so a data copy
-- keeps IDs), real foreign keys, partial indexes. No triggers and none of
-- the legacy columns #402 dropped. Versions below 28 are SQLite-only
-- history.

CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 display_name text NOT NULL CHECK (display_name <> ''),
 created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE identities (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 provider text NOT NULL CHECK (provider <> ''),
 subject text NOT NULL CHECK (subject <> ''),
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE (provider, subject)
);
CREATE INDEX identities_user ON identities(user_id);

CREATE TABLE machines (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 label text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now(),
 created_by_user_id bigint NOT NULL DEFAULT 1 REFERENCES users(id),
 removed_at timestamptz,
 last_seen_at timestamptz,
 version text NOT NULL DEFAULT ''
);

CREATE TABLE machine_tokens (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 machine_id bigint NOT NULL REFERENCES machines(id) CHECK (machine_id <> 1),
 secret_hash bytea NOT NULL CHECK (octet_length(secret_hash) = 32),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX machine_tokens_machine ON machine_tokens(machine_id);

CREATE TABLE pairing_codes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 secret_hash bytea NOT NULL CHECK (octet_length(secret_hash) = 32),
 label text NOT NULL DEFAULT '',
 created_by_user_id bigint NOT NULL REFERENCES users(id),
 created_at timestamptz NOT NULL DEFAULT now(),
 expires_at timestamptz NOT NULL,
 redeemed_at timestamptz,
 machine_id bigint REFERENCES machines(id),
 CHECK ((redeemed_at IS NULL) = (machine_id IS NULL))
);

CREATE TABLE harness_connections (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 machine_id bigint NOT NULL DEFAULT 1 REFERENCES machines(id),
 harness text NOT NULL CHECK (harness <> ''),
 created_at timestamptz NOT NULL DEFAULT now(),
 auto_complete boolean NOT NULL DEFAULT true,
 -- The instance identity the harness's connector verified.
 identity text NOT NULL DEFAULT '',
 stable_identity boolean NOT NULL DEFAULT false,
 -- Display name of the instance.
 label text NOT NULL DEFAULT '',
 active boolean NOT NULL DEFAULT true,
 retired_at timestamptz,
 forgotten_at timestamptz,
 new_task_config jsonb CHECK (new_task_config IS NULL OR jsonb_typeof(new_task_config) = 'object'),
 CHECK (active OR retired_at IS NOT NULL),
 CHECK (forgotten_at IS NULL OR NOT active)
);
CREATE UNIQUE INDEX harness_connection_active ON harness_connections(machine_id, harness) WHERE active;
CREATE UNIQUE INDEX harness_connection_identity ON harness_connections(machine_id, harness, identity) WHERE stable_identity AND identity <> '';

CREATE TABLE session_identities (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 connection_id bigint NOT NULL REFERENCES harness_connections(id),
 external_id text NOT NULL,
 UNIQUE (connection_id, external_id)
);

CREATE TABLE shared_paths (
 connection_id bigint NOT NULL REFERENCES harness_connections(id),
 harness_root text NOT NULL,
 stage_root text NOT NULL,
 PRIMARY KEY (connection_id, harness_root)
);

CREATE TABLE t3_connection (
 machine_id bigint PRIMARY KEY REFERENCES machines(id),
 client_id text,
 token text,
 expires_at timestamptz,
 last_error text,
 last_full_sync_at timestamptz,
 t3_url text,
 updated_at timestamptz NOT NULL DEFAULT now(),
 public_url text,
 admin_token text
);

CREATE TABLE opencode_settings (
 machine_id bigint PRIMARY KEY REFERENCES machines(id),
 endpoint text NOT NULL DEFAULT '',
 browser_endpoint text NOT NULL DEFAULT '',
 web_client text NOT NULL DEFAULT '',
 username text NOT NULL DEFAULT '',
 password text NOT NULL DEFAULT '',
 auth text NOT NULL DEFAULT 'none' CHECK (auth IN ('none', 'local', 'paired', 'basic')),
 token_issued_at timestamptz
);

CREATE TABLE preferences (
 id bigint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
 updated_at timestamptz NOT NULL DEFAULT now(),
 notify_events jsonb NOT NULL DEFAULT '["needs_input","failed","done","settled"]'
  CHECK (jsonb_typeof(notify_events) = 'array'),
 default_connection_id bigint REFERENCES harness_connections(id) ON DELETE SET NULL
);

CREATE TABLE projects (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title text NOT NULL,
 archived_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 origin text CHECK (origin IN ('discovered')),
 imported_connection_id bigint REFERENCES harness_connections(id),
 imported_at timestamptz,
 archive_owner text CHECK (archive_owner IN ('user', 'harness')),
 created_by_user_id bigint NOT NULL DEFAULT 1 REFERENCES users(id),
 source_machine_id bigint REFERENCES machines(id)
);

CREATE TABLE project_bindings (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id bigint NOT NULL REFERENCES projects(id),
 connection_id bigint NOT NULL REFERENCES harness_connections(id),
 external_project_id text NOT NULL,
 workspace text NOT NULL,
 revision integer NOT NULL DEFAULT 1,
 active boolean NOT NULL DEFAULT true,
 status text NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'missing', 'changed')),
 observed_workspace text,
 created_at timestamptz NOT NULL DEFAULT now(),
 -- manual: a user bound it; imported: discovery created the project for it;
 -- path: discovery bound it to the project at that path on this machine;
 -- remote: discovery bound it to the one project with the same origin
 -- remote and subproject on another machine.
 origin text NOT NULL DEFAULT 'manual' CHECK (origin IN ('manual', 'imported', 'path', 'remote'))
);
CREATE UNIQUE INDEX project_binding_active ON project_bindings(project_id, connection_id) WHERE active;
CREATE UNIQUE INDEX workspace_binding_active ON project_bindings(connection_id, external_project_id, workspace) WHERE active;

CREATE TABLE external_projects (
 connection_id bigint NOT NULL REFERENCES harness_connections(id),
 external_id text NOT NULL,
 title text NOT NULL,
 workspace text NOT NULL,
 available boolean NOT NULL,
 importable boolean NOT NULL DEFAULT false,
 archived boolean NOT NULL DEFAULT false,
 active_at timestamptz,
 declined_at timestamptz,
 repo text NOT NULL DEFAULT '',
 repo_path text NOT NULL DEFAULT '',
 PRIMARY KEY (connection_id, external_id, workspace)
);

CREATE TABLE schedules (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id bigint NOT NULL REFERENCES projects(id),
 title text NOT NULL,
 prompt text NOT NULL,
 workspace jsonb NOT NULL DEFAULT '{"type":"root"}' CHECK (jsonb_typeof(workspace) = 'object'),
 notes text NOT NULL DEFAULT '',
 cron text NOT NULL,
 tz text NOT NULL,
 paused boolean NOT NULL DEFAULT false,
 next_run_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 connection_id bigint NOT NULL DEFAULT 1 REFERENCES harness_connections(id),
 origin_session_id bigint REFERENCES session_identities(id),
 execution_config jsonb,
 created_by_user_id bigint NOT NULL DEFAULT 1 REFERENCES users(id),
 source_machine_id bigint REFERENCES machines(id)
);
CREATE INDEX schedules_due_idx ON schedules(next_run_at) WHERE NOT paused;
CREATE INDEX schedules_project_idx ON schedules(project_id);

CREATE TABLE task_trees (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title text NOT NULL CHECK (length(trim(title)) > 0),
 start_mode text NOT NULL DEFAULT 'auto' CHECK (start_mode IN ('auto', 'manual')),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'done', 'archived')),
 closed_at timestamptz,
 recorded_work boolean NOT NULL DEFAULT false,
 membership_revision integer NOT NULL DEFAULT 0,
 created_by_user_id bigint NOT NULL DEFAULT 1 REFERENCES users(id),
 source_machine_id bigint REFERENCES machines(id)
);

CREATE TABLE tasks (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id bigint NOT NULL REFERENCES projects(id),
 title text NOT NULL,
 prompt text NOT NULL,
 workspace jsonb NOT NULL DEFAULT '{"type":"root"}' CHECK (jsonb_typeof(workspace) = 'object'),
 state text NOT NULL DEFAULT 'backlog' CHECK (state IN (
  'backlog', 'launching', 'running', 'needs_input', 'done',
  'settled', 'failed', 'interrupted', 'cancelled'
 )),
 launch_attempt integer NOT NULL DEFAULT 0,
 last_error text,
 launched_at timestamptz,
 finished_at timestamptz,
 settled_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 launch_request_id text,
 start_at timestamptz,
 start_tz text,
 schedule_id bigint REFERENCES schedules(id) ON DELETE SET NULL,
 handoff boolean NOT NULL DEFAULT true,
 tree_id bigint REFERENCES task_trees(id) ON DELETE SET NULL,
 start_mode text CHECK (start_mode IN ('auto', 'manual')),
 adopted boolean NOT NULL DEFAULT false,
 ready_at timestamptz,
 archived_at timestamptz,
 recorded_work boolean NOT NULL DEFAULT false,
 acceptance_revision integer NOT NULL DEFAULT 0,
 acceptance_id bigint,
 scheduled_hold boolean NOT NULL DEFAULT false,
 connection_id bigint NOT NULL DEFAULT 1 REFERENCES harness_connections(id),
 session_id bigint REFERENCES session_identities(id),
 origin_session_id bigint REFERENCES session_identities(id),
 execution_config jsonb,
 created_by_user_id bigint NOT NULL DEFAULT 1 REFERENCES users(id),
 source_machine_id bigint REFERENCES machines(id),
 CONSTRAINT tasks_start_pair CHECK ((start_at IS NULL) = (start_tz IS NULL))
);
CREATE INDEX tasks_state_idx ON tasks(state);
CREATE INDEX tasks_project_id_idx ON tasks(project_id);
CREATE INDEX tasks_created_at_idx ON tasks(created_at);
CREATE INDEX tasks_due_start_idx ON tasks(start_at) WHERE state = 'backlog' AND start_at IS NOT NULL;
CREATE INDEX tasks_schedule_idx ON tasks(schedule_id) WHERE schedule_id IS NOT NULL;
CREATE INDEX tasks_tree_idx ON tasks(tree_id) WHERE tree_id IS NOT NULL;
CREATE INDEX tasks_archived_idx ON tasks(archived_at) WHERE archived_at IS NOT NULL;
CREATE UNIQUE INDEX task_session_identity ON tasks(session_id);

CREATE TABLE task_needs (
 task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
 need_id bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
 PRIMARY KEY (task_id, need_id),
 CHECK (task_id <> need_id)
);
CREATE INDEX task_needs_need_idx ON task_needs(need_id);

CREATE TABLE task_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
 from_state text,
 to_state text NOT NULL,
 detail text NOT NULL DEFAULT '',
 at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX task_events_task_id_idx ON task_events(task_id, at);

CREATE TABLE task_acceptances (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id bigint NOT NULL REFERENCES tasks(id),
 accepted_at timestamptz NOT NULL DEFAULT now(),
 captured_at timestamptz NOT NULL DEFAULT now(),
 provenance text NOT NULL CHECK (provenance IN ('user', 'historical_settlement', 'harness_settled', 'harness_archived')),
 -- Evidence: an immutable accepted snapshot; text keeps its exact bytes.
 evidence text NOT NULL CHECK (evidence IS JSON),
 note text NOT NULL DEFAULT '',
 source_session_id bigint REFERENCES session_identities(id)
);
CREATE INDEX task_acceptances_task ON task_acceptances(task_id, id);

CREATE TABLE acceptance_requests (
 task_id bigint NOT NULL REFERENCES tasks(id),
 request_id text NOT NULL,
 -- Evidence: idempotency compares these bytes.
 input text NOT NULL,
 result jsonb NOT NULL,
 PRIMARY KEY (task_id, request_id)
);

CREATE TABLE completion_inferences (
 task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
 execution_id text NOT NULL,
 signal text NOT NULL CHECK (signal IN ('settled', 'archived', 'reopened')),
 acceptance_id bigint,
 at timestamptz NOT NULL DEFAULT now(),
 UNIQUE (task_id, execution_id)
);

CREATE TABLE execution_attempts (
 task_id bigint NOT NULL REFERENCES tasks(id),
 attempt integer NOT NULL,
 intent jsonb,
 checkpoint jsonb NOT NULL DEFAULT '{"version":0,"data":null}',
 phase text NOT NULL CHECK (phase IN ('prepared', 'unconfirmed', 'confirmed', 'rejected')),
 revision integer NOT NULL DEFAULT 0,
 error text NOT NULL DEFAULT '',
 retry_at timestamptz,
 retry_count integer NOT NULL DEFAULT 0,
 observed_session jsonb CHECK (observed_session IS NULL OR jsonb_typeof(observed_session) = 'object'),
 PRIMARY KEY (task_id, attempt)
);

CREATE TABLE execution_observations (
 session_id bigint PRIMARY KEY REFERENCES session_identities(id),
 observation jsonb NOT NULL,
 observed_at timestamptz NOT NULL DEFAULT now(),
 unavailable_reason text NOT NULL DEFAULT ''
);

CREATE TABLE journal_entries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind text NOT NULL CHECK (kind IN ('note', 'event')),
 task_id bigint,
 tree_id bigint,
 source_task_id bigint,
 attempt integer,
 category text NOT NULL DEFAULT '' CHECK (category IN ('', 'finding', 'decision', 'blocker', 'outcome')),
 text text NOT NULL DEFAULT '',
 event_type text NOT NULL DEFAULT '',
 from_tree_id bigint,
 to_tree_id bigint,
 request_id text,
 created_at timestamptz NOT NULL DEFAULT now(),
 source_session_id bigint REFERENCES session_identities(id),
 created_by_user_id bigint NOT NULL DEFAULT 1 REFERENCES users(id),
 source_machine_id bigint REFERENCES machines(id),
 CHECK (task_id IS NOT NULL OR tree_id IS NOT NULL),
 CHECK (kind <> 'note' OR ((task_id IS NULL) <> (tree_id IS NULL) AND request_id IS NOT NULL AND event_type = ''))
);
CREATE UNIQUE INDEX journal_task_request ON journal_entries(task_id, request_id) WHERE kind = 'note' AND task_id IS NOT NULL;
CREATE UNIQUE INDEX journal_tree_request ON journal_entries(tree_id, request_id) WHERE kind = 'note' AND tree_id IS NOT NULL;
CREATE INDEX journal_task_read ON journal_entries(task_id, kind, id DESC);
CREATE INDEX journal_tree_read ON journal_entries(tree_id, kind, id DESC);
CREATE INDEX journal_source_read ON journal_entries(tree_id, source_task_id, id DESC);
CREATE INDEX journal_task_category ON journal_entries(task_id, category, id DESC);
CREATE INDEX journal_tree_category ON journal_entries(tree_id, category, id DESC);

CREATE TABLE journal_launch_context (
 task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
 attempt integer NOT NULL,
 instructions text NOT NULL,
 PRIMARY KEY (task_id, attempt)
);

CREATE TABLE task_launch_claims (
 task_id bigint NOT NULL REFERENCES tasks(id),
 attempt integer NOT NULL,
 PRIMARY KEY (task_id, attempt)
);

CREATE TABLE task_launch_destinations (
 task_id bigint NOT NULL REFERENCES tasks(id),
 attempt integer NOT NULL,
 connection_id bigint NOT NULL REFERENCES harness_connections(id),
 external_project_id text NOT NULL,
 workspace text NOT NULL,
 binding_id bigint NOT NULL REFERENCES project_bindings(id),
 binding_revision integer NOT NULL,
 PRIMARY KEY (task_id, attempt)
);

CREATE TABLE task_launch_inputs (
 task_id bigint NOT NULL,
 attempt integer NOT NULL,
 source_task_id bigint NOT NULL,
 acceptance_id bigint NOT NULL REFERENCES task_acceptances(id),
 PRIMARY KEY (task_id, attempt, source_task_id),
 FOREIGN KEY (task_id, attempt) REFERENCES task_launch_claims(task_id, attempt)
);

CREATE TABLE task_launch_bases (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
 attempt integer NOT NULL,
 base_ref text NOT NULL,
 start_from_origin boolean NOT NULL,
 source text NOT NULL CHECK (source IN ('predecessor', 'fallback')),
 source_task_id bigint,
 source_title text NOT NULL DEFAULT '',
 reason text,
 created_at timestamptz NOT NULL DEFAULT now(),
 source_session_id bigint REFERENCES session_identities(id),
 UNIQUE (task_id, attempt)
);

CREATE TABLE task_handoffs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
 attempt integer NOT NULL,
 source_task_id bigint,
 source_title text NOT NULL DEFAULT '',
 status text NOT NULL CHECK (status IN ('sent', 'skipped')),
 text text NOT NULL DEFAULT '',
 reason text,
 created_at timestamptz NOT NULL DEFAULT now(),
 source_session_id bigint REFERENCES session_identities(id),
 UNIQUE (task_id, attempt, source_task_id)
);

CREATE TABLE task_attachments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id bigint REFERENCES tasks(id) ON DELETE CASCADE,
 name text NOT NULL,
 mime_type text NOT NULL CHECK (mime_type IN ('image/png', 'image/jpeg', 'image/gif', 'image/webp')),
 size_bytes integer NOT NULL CHECK (size_bytes BETWEEN 1 AND 10485760),
 data bytea NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 schedule_id bigint REFERENCES schedules(id) ON DELETE CASCADE,
 CONSTRAINT task_attachments_one_owner CHECK (task_id IS NULL OR schedule_id IS NULL)
);
CREATE INDEX task_attachments_task_idx ON task_attachments(task_id, id);
CREATE INDEX task_attachments_staged_idx ON task_attachments(created_at) WHERE task_id IS NULL AND schedule_id IS NULL;
CREATE INDEX task_attachments_schedule_idx ON task_attachments(schedule_id, id) WHERE schedule_id IS NOT NULL;

CREATE TABLE schedule_runs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 schedule_id bigint NOT NULL REFERENCES schedules(id) ON DELETE CASCADE,
 fire_at timestamptz NOT NULL,
 outcome text NOT NULL CHECK (outcome IN ('started', 'skipped', 'missed', 'manual')),
 task_id bigint REFERENCES tasks(id) ON DELETE SET NULL,
 detail text NOT NULL DEFAULT '',
 at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX schedule_runs_schedule_idx ON schedule_runs(schedule_id, id DESC);

CREATE TABLE notifications (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event text NOT NULL CONSTRAINT notifications_event_check
  CHECK (event IN ('needs_input', 'ready', 'done', 'failed', 'settled')),
 task_id bigint REFERENCES tasks(id) ON DELETE SET NULL,
 title text NOT NULL,
 project_title text,
 url text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 read_at timestamptz,
 session_id bigint REFERENCES session_identities(id)
);
CREATE INDEX notifications_created_idx ON notifications(created_at DESC);
CREATE INDEX notifications_unread_idx ON notifications(id) WHERE read_at IS NULL;

CREATE TABLE threads (
 t3_thread_id text PRIMARY KEY,
 t3_project_id text NOT NULL,
 title text NOT NULL DEFAULT '',
 status text NOT NULL,
 settled boolean NOT NULL DEFAULT false,
 settled_at timestamptz,
 pending_request_count integer NOT NULL DEFAULT 0,
 model text,
 runtime_mode text,
 interaction_mode text,
 branch text,
 worktree_path text,
 parent_thread_id text,
 relationship text,
 created_at timestamptz NOT NULL,
 updated_at timestamptz NOT NULL,
 synced_at timestamptz NOT NULL DEFAULT now(),
 observed_state text,
 archived boolean NOT NULL DEFAULT false,
 active_run_id text,
 latest_run_id text,
 run_started_at timestamptz,
 run_ended_at timestamptz,
 last_word_text text,
 last_word_preview text,
 last_word_truncated boolean NOT NULL DEFAULT false,
 last_word_run_id text,
 last_word_at timestamptz,
 last_word_checked_at timestamptz,
 session_id bigint REFERENCES session_identities(id),
 stage_project_id bigint REFERENCES projects(id),
 execution_state text
);
CREATE INDEX threads_created_at_idx ON threads(created_at);
CREATE UNIQUE INDEX thread_session_identity ON threads(session_id);

CREATE TABLE push_subscriptions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 endpoint text NOT NULL UNIQUE,
 p256dh text NOT NULL,
 auth text NOT NULL,
 user_agent text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 last_success_at timestamptz,
 last_error text
);

CREATE TABLE push_vapid (
 id bigint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
 public_key text NOT NULL,
 private_key text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE snippets (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL UNIQUE,
 body text NOT NULL CONSTRAINT snippets_body_check CHECK (body <> ''),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 project_id bigint REFERENCES projects(id) ON DELETE CASCADE
);

