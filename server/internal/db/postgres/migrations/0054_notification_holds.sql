-- +goose Up
-- Notification hold (ADR 0013): a member's needs_input notification waits
-- steering_hold_seconds (0 off, max 3600) while the tree's steerer can
-- answer it. The notification row is inserted only at release (the SSE
-- cursor is id-ordered). One held row per task.
ALTER TABLE task_trees ADD COLUMN steering_hold_seconds integer NOT NULL DEFAULT 300 CHECK (steering_hold_seconds BETWEEN 0 AND 3600);
-- note: why a released notification came late ("Steerer did not answer").
ALTER TABLE notifications ADD COLUMN note text;
CREATE TABLE notification_holds (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
 state_revision bigint NOT NULL,
 steerer_id bigint NOT NULL REFERENCES tree_steerers(id) ON DELETE CASCADE,
 held_at timestamptz NOT NULL,
 hold_until timestamptz NOT NULL,
 state text NOT NULL DEFAULT 'held' CHECK (state IN ('held', 'released', 'cancelled', 'escalated')),
 notification_id bigint REFERENCES notifications(id) ON DELETE SET NULL,
 reason text,
 attribution text
);
CREATE UNIQUE INDEX notification_holds_held_idx ON notification_holds(task_id) WHERE state = 'held';
CREATE INDEX notification_holds_steerer_idx ON notification_holds(steerer_id, state);
