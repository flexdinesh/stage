package service

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"io"
	"strconv"
	"strings"
)

// Generator marks definitions `stage service` wrote (and may rewrite or
// remove); Schema versions their layout.
const (
	Generator = "stage-service"
	Schema    = 1
)

// Restart policy and timeouts shared by both definitions (docs/service.md).
const (
	StopTimeoutSec = 110 // > serve.ShutdownTimeout (100s)
	// WorkerStopTimeoutSec bounds a worker's shutdown (it cancels its
	// calls and closes its channel at once).
	WorkerStopTimeoutSec = 30
	StartTimeoutSec      = 120
	ThrottleSec          = 10 // launchd minimum respawn interval
	// ExitConflict: data dir held by another server; ExitConfig: invalid
	// configuration. Neither is retried by systemd.
	ExitConflict = 75
	ExitConfig   = 78
)

// Spec is what a definition encodes.
type Spec struct {
	Identity   string
	Name       string // unit or label
	Exe        string
	Env        []KV // pinned
	StderrPath string
	// Role is what the service runs: the server (zero) or a worker.
	Role Role
}

// Args is the managed command line.
func (s Spec) Args() []string {
	if s.Role == RoleWorker {
		return []string{s.Exe, "worker", "run", "--managed"}
	}
	return []string{s.Exe, "serve", "--managed"}
}

func (s Spec) stopTimeout() int {
	if s.Role == RoleWorker {
		return WorkerStopTimeoutSec
	}
	return StopTimeoutSec
}

func (s Spec) description() string {
	if s.Role == RoleWorker {
		return fmt.Sprintf("Stage worker (%s)", s.Identity)
	}
	return fmt.Sprintf("Stage server (%s)", s.Identity)
}

// RenderUnit is the systemd user unit.
func RenderUnit(s Spec) []byte {
	var b strings.Builder
	cmd := s.Role.Command()
	fmt.Fprintf(&b, "# Generated by `%s` (identity %s). `%s start` may rewrite it;\n", cmd, s.Identity, cmd)
	fmt.Fprintf(&b, "# put local overrides in a drop-in: systemctl --user edit %s\n", s.Name)
	b.WriteString("[Unit]\n")
	fmt.Fprintf(&b, "Description=%s\n", s.description())
	b.WriteString("StartLimitIntervalSec=5min\nStartLimitBurst=10\n\n")
	b.WriteString("[Service]\nType=notify\n")
	var args []string
	for _, a := range s.Args() {
		args = append(args, quoteExecArg(a))
	}
	fmt.Fprintf(&b, "ExecStart=%s\n", strings.Join(args, " "))
	for _, kv := range s.Env {
		fmt.Fprintf(&b, "Environment=%s\n", quoteSystemd(kv.Key+"="+kv.Value, false))
	}
	syslogID := s.Identity
	if s.Role == RoleWorker {
		syslogID += "-worker"
	}
	fmt.Fprintf(&b, "SyslogIdentifier=%s\n", syslogID)
	b.WriteString("Restart=on-failure\nRestartSec=2s\nRestartSteps=5\nRestartMaxDelaySec=60s\n")
	fmt.Fprintf(&b, "RestartPreventExitStatus=%d %d\n", ExitConflict, ExitConfig)
	fmt.Fprintf(&b, "TimeoutStartSec=%ds\nTimeoutStopSec=%ds\n\n", StartTimeoutSec, s.stopTimeout())
	b.WriteString("[Install]\nWantedBy=default.target\n\n")
	fmt.Fprintf(&b, "[X-Stage]\nGenerator=%s\nSchema=%d\nExe=%s\n", Generator, Schema, s.Exe)
	if s.Role == RoleWorker {
		fmt.Fprintf(&b, "Role=%s\n", s.Role)
	}
	return []byte(b.String())
}

// quoteExecArg quotes one ExecStart word: '%' and '$' are always escaped
// (specifiers and variable expansion); a word with whitespace, quotes or
// backslashes is double-quoted.
func quoteExecArg(a string) string { return quoteSystemd(a, true) }

func quoteSystemd(v string, dollar bool) string {
	v = strings.ReplaceAll(v, "%", "%%")
	if dollar {
		v = strings.ReplaceAll(v, "$", "$$")
	}
	if v != "" && !strings.ContainsAny(v, " \t\"'\\;") {
		return v
	}
	v = strings.ReplaceAll(v, `\`, `\\`)
	v = strings.ReplaceAll(v, `"`, `\"`)
	return `"` + v + `"`
}

func unquoteSystemd(v string, dollar bool) string {
	if len(v) >= 2 && v[0] == '"' && v[len(v)-1] == '"' {
		inner := v[1 : len(v)-1]
		var b strings.Builder
		for i := 0; i < len(inner); i++ {
			if inner[i] == '\\' && i+1 < len(inner) {
				i++
			}
			b.WriteByte(inner[i])
		}
		v = b.String()
	}
	if dollar {
		v = strings.ReplaceAll(v, "$$", "$")
	}
	return strings.ReplaceAll(v, "%%", "%")
}

// RenderPlist is the launchd agent property list.
func RenderPlist(s Spec) []byte {
	var b bytes.Buffer
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
`)
	fmt.Fprintf(&b, "<!-- Generated by `stage service` (generator=%s schema=%d). `stage service start` may rewrite it. -->\n", Generator, Schema)
	b.WriteString("<plist version=\"1.0\">\n<dict>\n")
	key := func(k string) { fmt.Fprintf(&b, "  <key>%s</key>", esc(k)) }
	key("Label")
	fmt.Fprintf(&b, "<string>%s</string>\n", esc(s.Name))
	key("ProgramArguments")
	b.WriteString("\n  <array>\n")
	for _, a := range s.Args() {
		fmt.Fprintf(&b, "    <string>%s</string>\n", esc(a))
	}
	b.WriteString("  </array>\n")
	key("EnvironmentVariables")
	b.WriteString("\n  <dict>\n")
	env := append([]KV{{"STAGE_SERVICE_SCHEMA", strconv.Itoa(Schema)}}, s.Env...)
	for _, kv := range env {
		fmt.Fprintf(&b, "    <key>%s</key><string>%s</string>\n", esc(kv.Key), esc(kv.Value))
	}
	b.WriteString("  </dict>\n")
	key("RunAtLoad")
	b.WriteString("<true/>\n")
	key("KeepAlive")
	b.WriteString("\n  <dict>\n    <key>SuccessfulExit</key><false/>\n  </dict>\n")
	key("ThrottleInterval")
	fmt.Fprintf(&b, "<integer>%d</integer>\n", ThrottleSec)
	key("ExitTimeOut")
	fmt.Fprintf(&b, "<integer>%d</integer>\n", s.stopTimeout())
	key("StandardOutPath")
	fmt.Fprintf(&b, "<string>%s</string>\n", esc(s.StderrPath))
	key("StandardErrorPath")
	fmt.Fprintf(&b, "<string>%s</string>\n", esc(s.StderrPath))
	b.WriteString("</dict>\n</plist>\n")
	return b.Bytes()
}

func esc(s string) string {
	var b bytes.Buffer
	_ = xml.EscapeText(&b, []byte(s))
	return b.String()
}

// Marker is what ParseDefinition reads back from a definition.
type Marker struct {
	Generated bool // carries Generator: ours to rewrite or remove
	Schema    int
	Exe       string
	Env       []KV // pinned
}

// ParseDefinition reads a unit (Linux) or plist (macOS).
func ParseDefinition(goos string, b []byte) Marker {
	if goos == "darwin" {
		return parsePlist(b)
	}
	return parseUnit(b)
}

func parseUnit(b []byte) Marker {
	var m Marker
	section := ""
	for line := range strings.SplitSeq(string(b), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			section = line
			continue
		}
		k, v, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		switch {
		case section == "[X-Stage]" && k == "Generator":
			m.Generated = v == Generator
		case section == "[X-Stage]" && k == "Schema":
			m.Schema, _ = strconv.Atoi(v)
		case section == "[X-Stage]" && k == "Exe":
			m.Exe = v
		case section == "[Service]" && k == "Environment":
			if ek, ev, ok := strings.Cut(unquoteSystemd(v, false), "="); ok {
				m.Env = append(m.Env, KV{ek, ev})
			}
		}
	}
	return m
}

func parsePlist(b []byte) Marker {
	var m Marker
	m.Generated = bytes.Contains(b, []byte("generator="+Generator+" "))
	top, err := decodePlist(b)
	if err != nil {
		return Marker{}
	}
	if args, ok := top["ProgramArguments"].([]any); ok && len(args) > 0 {
		if s, ok := args[0].(string); ok {
			m.Exe = s
		}
	}
	if env, ok := top["EnvironmentVariables"].(map[string]any); ok {
		if s, ok := env["STAGE_SERVICE_SCHEMA"].(string); ok {
			m.Schema, _ = strconv.Atoi(s)
		}
		for _, k := range PinnableKeys {
			if v, ok := env[k].(string); ok {
				m.Env = append(m.Env, KV{k, v})
			}
		}
	}
	return m
}

// decodePlist decodes the top-level dict of an XML plist (string, integer,
// true/false, array and dict values).
func decodePlist(b []byte) (map[string]any, error) {
	d := xml.NewDecoder(bytes.NewReader(b))
	d.Strict = false
	for {
		tok, err := d.Token()
		if err != nil {
			return nil, err
		}
		if se, ok := tok.(xml.StartElement); ok && se.Name.Local == "dict" {
			v, err := plistDict(d)
			return v, err
		}
	}
}

func plistValue(d *xml.Decoder, se xml.StartElement) (any, error) {
	switch se.Name.Local {
	case "dict":
		return plistDict(d)
	case "array":
		var out []any
		for {
			tok, err := d.Token()
			if err != nil {
				return nil, err
			}
			switch t := tok.(type) {
			case xml.StartElement:
				v, err := plistValue(d, t)
				if err != nil {
					return nil, err
				}
				out = append(out, v)
			case xml.EndElement:
				return out, nil
			}
		}
	case "true", "false":
		if err := d.Skip(); err != nil {
			return nil, err
		}
		return se.Name.Local == "true", nil
	default:
		var s string
		if err := d.DecodeElement(&s, &se); err != nil {
			return nil, err
		}
		return s, nil
	}
}

func plistDict(d *xml.Decoder) (map[string]any, error) {
	out := map[string]any{}
	key := ""
	for {
		tok, err := d.Token()
		if err == io.EOF {
			return out, nil
		}
		if err != nil {
			return nil, err
		}
		switch t := tok.(type) {
		case xml.StartElement:
			if t.Name.Local == "key" {
				if err := d.DecodeElement(&key, &t); err != nil {
					return nil, err
				}
				continue
			}
			v, err := plistValue(d, t)
			if err != nil {
				return nil, err
			}
			out[key] = v
		case xml.EndElement:
			return out, nil
		}
	}
}
